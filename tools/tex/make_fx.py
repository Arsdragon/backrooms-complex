def smoke():
    """Мягкие клубы газа/дыма: атлас 2×2, почти белый, альфа — плотность (к краю квадрата строго ноль)"""
    n = 256
    tiles = []
    for k in range(4):
        y, x = np.mgrid[0:n, 0:n] / (n - 1) * 2.0 - 1.0
        rr = np.random.default_rng(700 + k)
        # клуб — несколько вложенных «кочанов» разного размера, края рвёт крупный шум
        d = np.zeros((n, n))
        for _ in range(7):
            ang = rr.uniform(0, 2 * np.pi)
            rad = rr.uniform(0.0, 0.32)
            cx, cy = np.cos(ang) * rad, np.sin(ang) * rad
            s = rr.uniform(0.22, 0.4)
            d = np.maximum(d, np.exp(-((x - cx) ** 2 + (y - cy) ** 2) / (2 * s * s)) * rr.uniform(0.7, 1.0))
        f1 = noise(n, n, 3.2, 710 + k)
        f2 = noise(n, n, 2.4, 720 + k)
        wx = (f1 - 0.5) * 0.5
        wy = (f2 - 0.5) * 0.5
        yy, xx = np.mgrid[0:n, 0:n].astype(float)
        d = ndimage.map_coordinates(d, [np.clip(yy + wy * n * 0.25, 0, n - 1), np.clip(xx + wx * n * 0.25, 0, n - 1)], order=1)
        r = np.sqrt(x * x + y * y)
        dens = d * sstep(1.0, 0.6, r) * (0.7 + 0.5 * (blur(f2, 3.0) - 0.5))
        dens = sstep(0.04, 0.85, dens) ** 1.1
        # внутри плотнее и чуть светлее, по краю — тонкие «волокна»
        lum = 0.9 + 0.1 * sstep(0.2, 0.8, dens)
        tiles.append(np.dstack([lum, lum, lum, dens]))
    top = np.hstack([tiles[0], tiles[1]])
    bot = np.hstack([tiles[2], tiles[3]])
    save("fx_smoke", np.vstack([top, bot]))


