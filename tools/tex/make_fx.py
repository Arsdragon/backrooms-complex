def earth():
    """Земля 4096×2048 (равнопромежуточная): материки по контурам выше, рельеф, пустыни, льды.
    Цвета приглушённые, как на снимках с орбиты: тёмная оливковая зелень, бурые поля, рыжевато-серые пустыни;
    горы — лишь чуть темнее и рельефнее, снег — редкими пятнами на самых высоких гребнях (июль).
    RGB — цвет суши (продолжен в море), альфа — мягкая маска суши"""
    W, H = 4096, 2048
    land, lakes = raster_land(W, H)
    land = land.astype(float)
    # береговая линия: размытие + шум → фьорды, островки, без ломаных отрезков
    lb = blur(land, 2.2)
    cn = noise(H, W, 1.6, 1001)
    land = sstep(0.42, 0.58, lb + (cn - 0.5) * 0.22)
    lake = sstep(0.4, 0.6, blur(lakes.astype(float), 1.2))
    land = land * (1.0 - lake)
    lat = (0.5 - (np.arange(H) + 0.5) / H)[:, None] * 180.0
    lon = ((np.arange(W) + 0.5) / W - 0.5)[None, :] * 360.0
    LAT = np.broadcast_to(lat, (H, W))
    LON = np.broadcast_to(lon, (H, W))
    # искажённые координаты для климатических полей — без круглых пятен
    wx = noise(H, W, 3.0, 1010)
    wy = noise(H, W, 3.0, 1011)
    LONw = LON + (wx - 0.5) * 9.0
    LATw = LAT + (wy - 0.5) * 5.0
    rng_m, snowy = mountains(LON, LAT)
    dry = dryness(LONw, LATw)
    wet = rivers(LON, LAT)
    n1 = noise(H, W, 2.2, 1002)
    n2 = noise(H, W, 1.8, 1003)
    n3 = noise(H, W, 3.0, 1004)
    fields = band(H, W, 700, 2000, 1006)
    patch = band(H, W, 120, 500, 1008)          # леса и пашни пятнами в десятки км
    # горы: гребни (ridged noise) внутри полос хребтов
    r1 = 1.0 - np.abs(noise(H, W, 2.0, 1005) * 2.0 - 1.0)
    r2 = 1.0 - np.abs(noise(H, W, 1.6, 1007) * 2.0 - 1.0)
    ridges = r1 ** 2 * 0.65 + r2 ** 3 * 0.35
    elev = rng_m * (0.3 + 0.9 * ridges)
    dry = np.clip(dry + (n1 - 0.5) * 0.3 - wet * 1.5, 0, 1)
    alat = np.abs(LAT)
    # растительность по широте (приглушённая: с орбиты зелень — тёмная оливковая)
    trop = lerp3(rgb(20, 34, 18), rgb(30, 44, 24), n2)
    forest = lerp3(rgb(34, 44, 28), rgb(46, 54, 34), n2)
    farm = lerp3(rgb(78, 80, 56), rgb(108, 102, 74), n1 * 0.5 + fields * 0.5)
    temp = lerp3(forest, farm, sstep(0.35, 0.65, patch * 0.7 + fields * 0.3))
    boreal = lerp3(rgb(24, 32, 24), rgb(36, 42, 32), n2)
    tundra = lerp3(rgb(72, 70, 60), rgb(96, 90, 78), n2)
    veg = lerp3(trop, temp, sstep(14, 30, np.abs(LATw)))
    veg = lerp3(veg, boreal, sstep(52, 60, np.abs(LATw)))
    veg = lerp3(veg, tundra, sstep(65, 71, alat))
    semi = lerp3(rgb(104, 94, 70), rgb(132, 116, 86), n2 * 0.6 + fields * 0.4)
    sand = lerp3(rgb(180, 142, 100), rgb(204, 170, 126), sstep(0.3, 0.7, n1))
    rock = lerp3(rgb(104, 82, 64), rgb(136, 108, 82), n2)
    desert_c = lerp3(sand, rock, sstep(0.45, 0.75, n3 * 0.7 + patch * 0.3) * 0.8)
    col = lerp3(veg, semi, sstep(0.2, 0.5, dry))
    col = lerp3(col, desert_c, sstep(0.5, 0.8, dry))
    # горы: чуть темнее и серее (лес и скалы); снег — только пятна на самых высоких гребнях
    mtn = lerp3(rgb(62, 60, 50), rgb(100, 94, 82), ridges)
    col = lerp3(col, mtn, sstep(0.2, 0.7, elev) * 0.45)
    snow_line = 1.02 - sstep(30, 65, alat) * 0.4
    fine = 1.0 - np.abs(noise(H, W, 1.4, 1009) * 2.0 - 1.0)
    snow = sstep(snow_line, snow_line + 0.12, elev * (0.75 + 0.35 * fine)) * snowy * sstep(0.45, 0.7, n3)
    ice = sstep(77, 81, LAT) + sstep(-60, -64, LAT)
    ice = np.clip(ice + greenland_ice(LON, LAT) * sstep(0.2, 0.6, n3 + 0.3), 0, 1)
    col = lerp3(col, rgb(214, 218, 222), np.clip(snow * 0.8 + ice, 0, 1))
    # светотень рельефа: свет с северо-запада, мягкая
    hs = blur(elev, 1.2, True)
    gy, gx = np.gradient(hs)
    shade = np.clip(1.0 + (gy - gx) * 7.0, 0.82, 1.14)
    col *= shade[..., None]
    # RGB — цвет суши, продолженный в море (берег рисует шейдер по альфе, чётко при любом увеличении);
    # альфа — мягкая маска суши (0,5 — линия берега), море и шельф шейдер красит сам
    sea = land < 0.5
    idx = ndimage.distance_transform_edt(sea, return_distances=False, return_indices=True)
    col = col[idx[0], idx[1]]
    col = np.dstack([blur(col[..., k], 0.7) for k in range(3)])
    a = blur((land > 0.5).astype(float), 2.4)
    save("fx_earth", np.dstack([col, a]))


def _swirl(cy, cx, H, W, y0, x0, rad, turns):
    """Вихрь (циклон): поворот координат вокруг центра, сильнее у центра — «запятая» облачности"""
    xi = np.arange(int(x0 - rad * 2.5), int(x0 + rad * 2.5))
    xs = xi % W
    y1, y2 = int(max(y0 - rad * 2.5, 0)), int(min(y0 + rad * 2.5, H))
    yy = np.arange(y1, y2)[:, None].astype(float) - y0
    xx = (xi - x0)[None, :].astype(float)
    r = np.sqrt(yy * yy + xx * xx)
    ang = turns * np.exp(-(r / rad) ** 1.5)
    ca, sa = np.cos(ang), np.sin(ang)
    dy = yy * ca - xx * sa - yy
    dx = yy * sa + xx * ca - xx
    w = sstep(rad * 2.5, rad * 1.5, r)
    cy[y1:y2, xs] += dy * w
    cx[y1:y2, xs] += dx * w


def earth_clouds():
    """Облака Земли 4096×2048, ~60 % покрытия: фронты и циклоны средних широт («запятые»), пояс ВЗК
    с кучево-дождевыми скоплениями, поля пассатной кучёвки над океанами, перистые полосы; летом ясно над
    Сахарой и Аравией, над Средиземноморьем — разрозненная кучёвка"""
    W, H = 4096, 2048
    lat = (0.5 - (np.arange(H) + 0.5) / H)[:, None] * 180.0
    lon = ((np.arange(W) + 0.5) / W - 0.5)[None, :] * 360.0
    LAT = np.broadcast_to(lat, (H, W))
    LON = np.broadcast_to(lon, (H, W))
    rr = np.random.default_rng(1100)
    yy, xx = np.mgrid[0:H, 0:W].astype(float)
    # искажение координат: крупные волны + вихри циклонов
    cy = yy + (noise(H, W, 3.4, 1102) - 0.5) * 90.0
    cx = xx + (noise(H, W, 3.4, 1101) - 0.5) * 260.0
    cyc = [(54, -18, 1.0), (57, 12, 0.8), (47, -42, 1.0), (63, 38, 0.7), (45, 160, 1.0), (52, -165, 0.9),
           (-50, -30, 1.0), (-55, 40, 1.0), (-48, 110, 1.0), (-52, 170, 0.9), (-45, -100, 1.0), (60, 85, 0.6),
           (50, -140, 0.8), (-58, -70, 0.9), (40, 140, 0.7), (-40, 10, 0.8), (16, -60, 0.45), (18, 130, 0.5)]
    for la, lo, k in cyc:
        y0 = (90.0 - la) / 180.0 * H
        x0 = (lo + 180.0) / 360.0 * W
        rad = rr.uniform(110, 170) * k
        turns = rr.uniform(1.4, 2.3) * (1.0 if la > 0 else -1.0)
        _swirl(cy, cx, H, W, y0, x0, rad, turns)
    base = noise(H, W, 2.5, 1103)
    warped = ndimage.map_coordinates(base, [cy % H, cx % W], order=1, mode="wrap")
    streaks = ndimage.map_coordinates(noise(H, W, 2.0, 1108, aniso=(1.0, 3.0)), [cy % H, cx % W], order=1, mode="wrap")
    fine = noise(H, W, 2.3, 1104)
    cells = blur(band(H, W, 160, 420, 1105), 0.8)
    systems = noise(H, W, 3.6, 1109)
    alat = np.abs(LAT)
    # климатическая облачность: ВЗК, штормовые пояса, сухие субтропики
    cov = 0.62 + 0.14 * np.exp(-((LAT - 8.0) / 6.0) ** 2) + 0.12 * np.exp(-((alat - 55.0) / 12.0) ** 2)
    cov -= 0.1 * np.exp(-((alat - 27.0) / 8.0) ** 2)
    cov += (systems - 0.5) * 0.7
    clear = clear_sky(LON, LAT)
    cov -= clear * 0.5
    d = warped * 0.58 + streaks * 0.27 + fine * 0.15
    # плотные массы с мягким волокнистым краем
    c = sstep(1.0 - cov - 0.06, 1.0 - cov + 0.2, d)
    # кучёвка: ячейки (над морем — пассатные поля, над ясными районами — редкие «барашки»)
    cu_zone = np.clip(1.0 - np.abs(c - 0.25) * 2.5, 0, 1) + 0.35 * np.exp(-((alat - 18.0) / 10.0) ** 2)
    cu = sstep(0.58, 0.8, cells * 0.75 + fine * 0.35) * np.clip(cu_zone, 0, 1) * (1.0 - np.clip(clear * 1.6, 0, 1))
    c = np.maximum(c, cu * 0.7)
    # перистые полосы — полупрозрачные
    cir = sstep(0.62, 0.85, streaks) * (1.0 - clear * 0.7) * 0.4
    c = np.clip(np.maximum(c, cir) * (0.82 + 0.3 * fine), 0, 1)
    print("    cover: mean %.2f, >0.5: %.2f" % (c.mean(), (c > 0.5).mean()))
    save("fx_earth_clouds", blur(c, 0.8), "L")


