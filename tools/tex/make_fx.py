def noise(h, w=None, beta=2.0, seed=0, aniso=(1.0, 1.0)):
    """Периодический шум 1/f^beta (h×w), нормированный в 0..1"""
    w = w or h
    r = np.random.default_rng(seed)
    f = np.fft.fft2(r.standard_normal((h, w)))
    ky = np.fft.fftfreq(h)[:, None] * h / max(h, w) * aniso[1]
    kx = np.fft.fftfreq(w)[None, :] * w / max(h, w) * aniso[0]
    k = np.sqrt(kx * kx + ky * ky)
    k[0, 0] = 1.0
    f *= 1.0 / (k ** (beta / 2.0))
    f[0, 0] = 0
    o = np.real(np.fft.ifft2(f))
    o -= o.min()
    return o / (o.max() + 1e-9)


def band(h, w, lo, hi, seed):
    """Периодический шум в полосе частот (lo..hi периодов на кадр)"""
    r = np.random.default_rng(seed)
    f = np.fft.fft2(r.standard_normal((h, w)))
    ky = np.fft.fftfreq(h)[:, None] * h
    kx = np.fft.fftfreq(w)[None, :] * w
    k = np.sqrt(kx * kx + ky * ky)
    f *= np.clip((k - lo) / max(lo * 0.3, 1.0) + 1.0, 0, 1) * np.clip((hi - k) / max(hi * 0.3, 1.0) + 1.0, 0, 1)
    o = np.real(np.fft.ifft2(f))
    o -= o.min()
    return o / (o.max() + 1e-9)


def blur(a, s, wrap=True):
    return ndimage.gaussian_filter(a, s, mode="wrap" if wrap else "nearest")


def sstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def save(name, arr, mode=None):
    arr = np.clip(arr, 0, 1)
    img = Image.fromarray((arr * 255.0 + 0.5).astype(np.uint8))
    if mode:
        img = img.convert(mode)
    img.save(os.path.join(OUT, name + ".png"), optimize=True)
    print("  ", name, img.size, img.mode)


def rgb(*c):
    return np.array(c, dtype=float) / 255.0


def lerp3(a, b, t):
    t = np.asarray(t)[..., None]
    return a * (1.0 - t) + b * t


