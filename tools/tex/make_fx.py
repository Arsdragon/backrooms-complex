def canopy():
    """Лес сверху (тайл 48 м): кроны лиственных и хвойных, тени в просветах. Свет запечён с юго-запада"""
    n = 1024
    rr = np.random.default_rng(900)
    hgt = np.zeros((n, n))
    col = np.zeros((n, n, 3))
    yy, xx = np.mgrid[0:n, 0:n]
    leaf = noise(n, n, 1.2, 901)
    leaf2 = band(n, n, 60, 220, 902)
    pts = []
    tries = 0
    while len(pts) < 900 and tries < 30000:
        tries += 1
        p = rr.uniform(0, n, 2)
        conifer = rr.random() < 0.22          # равномерно: пятна пород рисует шейдер (иначе тайл виден решёткой)
        rad = rr.uniform(26, 40) if conifer else rr.uniform(48, 92)
        ok = True
        for q in pts:
            dx = (p[0] - q[0] + n / 2) % n - n / 2
            dy = (p[1] - q[1] + n / 2) % n - n / 2
            if dx * dx + dy * dy < ((rad + q[2]) * 0.62) ** 2:
                ok = False
                break
        if ok:
            pts.append((p[0], p[1], rad, conifer))
    for (px, py, rad, conifer) in pts:
        dx = (xx - px + n / 2) % n - n / 2
        dy = (yy - py + n / 2) % n - n / 2
        r = np.sqrt(dx * dx + dy * dy) / rad
        m = r < 1.0
        if conifer:
            # звёздчатая крона ели: остриё к центру, лучи-ветви
            ang = np.arctan2(dy, dx)
            star = 1.0 - r * (0.85 + 0.25 * np.sin(ang * 7 + px))
            h = np.clip(star, 0, 1) ** 0.8 * rad * 1.3
            c = rgb(28, 52, 30) * (0.85 + 0.3 * rr.random())
        else:
            h = np.sqrt(np.clip(1.0 - r * r, 0, 1)) * rad * 0.7
            tone = rr.random()
            c = lerp3(rgb(58, 88, 36), rgb(92, 112, 44), tone) * (0.85 + 0.25 * rr.random())
        upd = m & (h > hgt)
        hgt[upd] = h[upd]
        col[upd] = c
    # листва: мелкая рябь высоты
    hgt += (leaf - 0.5) * 9.0 + (leaf2 - 0.5) * 6.0
    hgt = np.where(col.sum(axis=2) > 0, hgt, -20.0)
    col[col.sum(axis=2) == 0] = rgb(22, 30, 16)
    # освещение по нормали карты высот + тени (солнце с юго-запада, высота ~40°)
    gy, gx = np.gradient(blur(hgt, 1.2))
    nrm = np.dstack([-gx * 0.5, -gy * 0.5, np.ones_like(gx)])
    nrm /= np.linalg.norm(nrm, axis=2, keepdims=True)
    L = np.array([-0.55, 0.5, 0.67])
    L /= np.linalg.norm(L)
    diff = np.clip((nrm * L).sum(axis=2), 0, 1)
    # тени: марш по карте высот в сторону солнца
    sh = np.ones((n, n))
    step = np.array([-L[0], -L[1]]) / np.hypot(L[0], L[1])
    tanv = L[2] / np.hypot(L[0], L[1])
    for s in range(2, 90, 3):
        ox, oy = int(round(-step[0] * s)), int(round(-step[1] * s))
        sh2 = np.roll(np.roll(hgt, oy, 0), ox, 1)
        sh = np.minimum(sh, np.where(sh2 > hgt + s * tanv, 0.35, 1.0))
    sh = blur(sh, 1.5)
    ao = np.clip((hgt + 20.0) / 60.0, 0.15, 1.0)
    light = (0.25 + 0.95 * diff * sh) * (0.55 + 0.45 * ao)
    out = col * light[..., None] * (0.85 + 0.3 * leaf2)[..., None]
    save("fx_canopy", np.clip(out * 1.25, 0, 1))


def desert():
    """Пустыня Большого Бассейна (тайл 8 м): пыльная светлая земля, гравий, кусты полыни с тенями"""
    n = 1024
    rr = np.random.default_rng(950)
    big = noise(n, n, 3.0, 951)
    mid = noise(n, n, 2.0, 952)
    fine = rr.random((n, n))
    grav = (rr.random((n, n)) > 0.985).astype(float)
    grav = np.clip(blur(grav, 0.9) * 6.0, 0, 1)
    base = lerp3(rgb(150, 138, 118), rgb(176, 164, 140), big)
    base *= (0.86 + (mid - 0.5) * 0.25 + (blur(fine, 0.6) - 0.5) * 0.35)[..., None]
    base = lerp3(base, rgb(98, 92, 84), grav * 0.7)
    # кусты: тёмные пятна + тень к северо-востоку
    shrub = np.zeros((n, n))
    yy, xx = np.mgrid[0:n, 0:n]
    lumpy = noise(n, n, 1.4, 953)
    for _ in range(46):
        px, py = rr.uniform(0, n, 2)
        rad = rr.uniform(22, 60)
        dx = (xx - px + n / 2) % n - n / 2
        dy = (yy - py + n / 2) % n - n / 2
        r = np.sqrt(dx * dx + dy * dy) / rad
        shrub = np.maximum(shrub, np.clip(1.0 - r + (lumpy - 0.5) * 0.9, 0, 1))
    shrub = sstep(0.05, 0.4, shrub)
    shadow = np.roll(np.roll(shrub, 14, 0), -10, 1)
    base *= (1.0 - 0.35 * shadow * (1.0 - shrub))[..., None]
    sh_col = lerp3(rgb(64, 70, 58), rgb(98, 102, 84), lumpy)
    base = lerp3(base, sh_col * (0.7 + 0.5 * fine)[..., None], shrub)
    save("fx_desert", base)


