    a = np.clip(rim * 0.85 + inner + hl, 0, 1) * sstep(1.0, 0.9, r)
    lum = np.clip(0.75 + hl * 0.3 + rim * 0.1, 0, 1)
    save("fx_bubble", np.dstack([lum, lum, lum, a]))


